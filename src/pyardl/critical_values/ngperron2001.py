def _interp(
    table: dict[int, dict[str, dict[float, float]]],
    n: int,
    stat: str,
    alpha: float,
) -> float:
    """Interpolate linearly in ``1/n``."""
    grid = np.array(sorted(table), dtype=np.float64)
    values = np.array([table[int(g)][stat][alpha] for g in grid])
    xs = 1.0 / grid
    order = np.argsort(xs)
    return float(np.interp(1.0 / n, xs[order], values[order]))


def m_critical_values(nobs: int, trend: str = "c") -> dict[str, dict[float, float]]:
    """Lower-tail critical values of the four M statistics.

    Parameters
    ----------
    nobs : int
        Length of the series tested, ``len(y)`` — the axis the table was
        simulated on, not the number of ADF regression rows.
    trend : {'c', 'ct'}, default 'c'

    Returns
    -------
    dict
        Statistic name, then level, then bound.

    Warns
    -----
    PyardlMethodologyWarning
        When ``nobs`` falls outside the simulated grid.

    Examples
    --------
    >>> from pyardl.critical_values.ngperron2001 import m_critical_values
    >>> cv = m_critical_values(200, "c")
    >>> round(cv["MZt"][0.05], 3)
    -2.015
    """
    if trend not in _M_TABLE:
        raise ValueError(f"trend={trend!r} must be 'c' or 'ct'.")
    table = _M_TABLE[trend]
    lo, hi = min(table), max(table)
    if nobs < lo or nobs > hi:
        warnings.warn(
            f"nobs={nobs} is outside the simulated grid [{lo}, {hi}]: the "
            "nearest endpoint is used.",
            PyardlMethodologyWarning,
            stacklevel=2,
        )
        nobs = min(max(nobs, lo), hi)
    return {s: {a: _interp(table, nobs, s, a) for a in _ALPHAS} for s in _STATS}
