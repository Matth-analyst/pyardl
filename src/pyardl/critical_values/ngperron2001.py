r"""Critical values for the M tests of Ng & Perron (2001).

Simulated in-house. Unlike the DF-GLS bounds, these have **no second
implementation to check against**: neither ``arch`` nor ``statsmodels``
provides the M statistics, so no independent library computes them.

Provenance
----------
Same protocol as the DF-GLS table: 100 000 replications of a Gaussian
random walk per grid point, GLS detrending under the local alternative,
lower-tail quantiles. Seeds recorded; see ``PROVENANCE.md``.

Because there is no external cross-check, the verification is internal
and rests on a property of the statistics themselves: :math:`MZ_t` has
the same limiting distribution as the DF-GLS statistic (Ng & Perron
2001, §2). The two tables are simulated independently within the same
run, and their entries converge as ``T`` grows — from a gap of 0.155 at
``T = 100`` down to 0.006 at ``T = 2000`` for the trend case at 10%.
A table built on a wrong formula would not converge on another one
derived separately.

All four statistics are **lower-tail**: reject the unit root when the
statistic falls below its bound.

References
----------
.. [1] Ng, S. & Perron, P. (2001). Lag length selection and the
       construction of unit root tests with good size and power.
       *Econometrica*, 69(6), 1519-1554.
"""

