#: Sample sizes covered, per trend.
DFGLS_GRID: tuple[int, ...] = tuple(sorted(_DFGLS_TABLE["c"]))


def _interp(table: dict[int, dict[float, float]], n: int, alpha: float) -> float:
    """Interpolate linearly in ``1/n``, where the curve is nearly affine."""
    grid = np.array(sorted(table), dtype=np.float64)
    values = np.array([table[int(g)][alpha] for g in grid])
    xs = 1.0 / grid
    order = np.argsort(xs)
    return float(np.interp(1.0 / n, xs[order], values[order]))


def dfgls_critical_values(nobs: int, trend: str = "c") -> dict[float, float]:
    """Left-tail critical values of the DF-GLS statistic.

    Parameters
    ----------
    nobs : int
        Length of the series tested. This is ``len(y)``, not the number
        of rows of the ADF regression: the asymptotics are in the sample
        size, and that is the axis the table was simulated on.
    trend : {'c', 'ct'}, default 'c'

    Returns
    -------
    dict
        Level to critical value, at 10%, 5% and 1%.

    Warns
    -----
    PyardlMethodologyWarning
        When ``nobs`` falls outside the simulated grid; the nearest
        endpoint is then used.

    Examples
    --------
    >>> from pyardl.critical_values.ers1996 import dfgls_critical_values
    >>> cv = dfgls_critical_values(200, "c")
    >>> round(cv[0.05], 3)
    -2.04
    """
    if trend not in _DFGLS_TABLE:
        raise ValueError(f"trend={trend!r} must be 'c' or 'ct'.")
    table = _DFGLS_TABLE[trend]
    lo, hi = min(table), max(table)
    if nobs < lo or nobs > hi:
        warnings.warn(
            f"nobs={nobs} is outside the simulated grid [{lo}, {hi}]: the "
            "nearest endpoint is used. Below the grid the test is severely "
            "under-powered anyway; above it the asymptotic values apply.",
            PyardlMethodologyWarning,
            stacklevel=2,
        )
        nobs = min(max(nobs, lo), hi)
    return {a: _interp(table, nobs, a) for a in _ALPHAS}
