r"""Critical values for the DF-GLS test (Elliott, Rothenberg & Stock 1996).

Simulated in-house, and cross-checked against an independent source.

Provenance
----------
The statistic has no closed-form finite-sample distribution, so the
values are obtained by simulating the null (a Gaussian random walk),
detrending it under the local alternative, and taking the lower-tail
quantiles of the resulting statistic. 100 000 replications per grid
point, seeds recorded; see ``PROVENANCE.md``.

A second source exists for this test — the response surfaces shipped
with ``arch`` (BSD-3), themselves re-simulated by their author. The two
agree within Monte Carlo error for ``T >= 100``. At ``T = 50`` they
differ by up to 0.037, always in the same direction, and an independent
size experiment settles which is right: our values deliver 5.07% at the
nominal 5% level, the response surface 4.72%. The difference is a
fitting artefact at the edge of the surface's range, not a disagreement
about the statistic — the statistics themselves match to 1e-15. See
OBS-6 of ``docs/VALIDATION_OBSERVATIONS.md``.

References
----------
.. [1] Elliott, G., Rothenberg, T. J. & Stock, J. H. (1996). Efficient
       tests for an autoregressive unit root. *Econometrica*, 64(4),
       813-836.
"""

