r"""Critical bounds for the CUSUM and CUSUM-of-squares stability tests.

Both tests of Brown, Durbin & Evans (1975) compare a path built from the
recursive residuals against a pair of boundaries. Crossing them is the
signal of parameter instability.

CUSUM
-----
Under the null of constant parameters, :math:`W_t` is approximately a
Brownian motion, and the test uses the pair of straight lines

.. math::

    \pm \left[ a\sqrt{T-k} + \frac{2a(t-k)}{\sqrt{T-k}} \right]

The coefficient :math:`a` solves the crossing-probability equation of
Brown, Durbin & Evans (1975, §2.3): it is the value for which a Brownian
motion crosses those lines with probability ``alpha``. Only three levels
were tabulated, and only those three are served here.

CUSUM of squares
----------------
The bands are :math:`E(S_t) \pm c_0` with :math:`E(S_t) = (t-k)/(T-k)`.
The value of :math:`c_0` depends on the number of recursive residuals
``n = T - k`` and on the level.

``c_0`` is obtained by simulation rather than transcription. This is not
a fallback: the statistic is genuinely distribution-free. If the
recursive residuals are i.i.d. :math:`N(0, \sigma^2)`, then

.. math::

    S_t = \frac{\sum_{s \le t} w_s^2}{\sum_{s \le n} w_s^2}

does not depend on :math:`\sigma^2` — it is a ratio of partial sums of
i.i.d. :math:`\chi^2_1` variables. The law of
:math:`\max_t |S_t - t/n|` therefore depends on ``n`` alone and can be
simulated exactly, to any precision.

The simulated values were cross-checked against their own asymptotic
limit: :math:`\sqrt{n/2}\,c_0` converges to the Kolmogorov quantile,
since :math:`S_t - t/n` behaves like a Brownian bridge of scale
:math:`\sqrt{2/n}` (the variance of a :math:`\chi^2_1` is 2). The ratio
rises monotonically to 0.98 at ``n = 1000``. See ``PROVENANCE.md``.

References
----------
.. [1] Brown, R. L., Durbin, J. & Evans, J. M. (1975). Techniques for
       testing the constancy of regression relationships over time.
       *Journal of the Royal Statistical Society B*, 37(2), 149-192.
"""

