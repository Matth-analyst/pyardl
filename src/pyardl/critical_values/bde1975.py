def _check_alpha(alpha: float) -> float:
    for a in _SUPPORTED_ALPHAS:
        if abs(alpha - a) < 1e-12:
            return a
    raise ValueError(
        f"alpha={alpha} is not available. The CUSUM and CUSUM-of-squares "
        f"bounds exist at {_SUPPORTED_ALPHAS} only."
    )


def cusum_a(alpha: float = 0.05) -> float:
    """Coefficient of the CUSUM boundary lines.

    Parameters
    ----------
    alpha : float, default 0.05
        Significance level. One of 0.10, 0.05, 0.01.

    Returns
    -------
    float
        The coefficient ``a`` entering ``+/- [a*sqrt(T-k) +
        2*a*(t-k)/sqrt(T-k)]``.

    Raises
    ------
    ValueError
        If ``alpha`` is not one of the three tabulated levels. No
        neighbouring level is silently substituted.

    Examples
    --------
    >>> from pyardl.critical_values.bde1975 import cusum_a
    >>> cusum_a(0.05)
    0.948
    """
    return CUSUM_A[_check_alpha(alpha)]


def cusumsq_c0(n: int, alpha: float = 0.05) -> float:
    """Half-width of the CUSUM-of-squares band.

    Parameters
    ----------
    n : int
        Number of recursive residuals, ``n = T - k``.
    alpha : float, default 0.05
        Significance level. One of 0.10, 0.05, 0.01.

    Returns
    -------
    float
        The value ``c0`` such that the band is ``(t-k)/(T-k) +/- c0``.

    Raises
    ------
    ValueError
        If ``n`` is below 4 (fewer recursive residuals than the statistic
        needs) or ``alpha`` is not tabulated.

    Warns
    -----
    PyardlMethodologyWarning
        When ``n`` exceeds the simulated grid. The asymptotic Kolmogorov
        approximation is then used, which widens the band slightly and so
        makes the test conservative rather than liberal.

    Notes
    -----
    Interpolation is linear in ``1/sqrt(n)``, the scale on which ``c0``
    is nearly affine, rather than in ``n`` where it is strongly convex.

    Examples
    --------
    >>> from pyardl.critical_values.bde1975 import cusumsq_c0
    >>> round(cusumsq_c0(100, 0.05), 4)
    0.1807
    """
    a = _check_alpha(alpha)
    if n < _N_MIN:
        raise ValueError(
            f"n={n} is too small: the CUSUM-of-squares statistic needs at "
            f"least {_N_MIN} recursive residuals."
        )
    if n > _N_MAX:
        from scipy.stats import kstwobign

        warnings.warn(
            f"n={n} exceeds the simulated grid (max {_N_MAX}): falling back "
            "to the asymptotic Kolmogorov approximation, which widens the "
            "band and makes the test conservative.",
            PyardlMethodologyWarning,
            stacklevel=2,
        )
        return float(kstwobign.ppf(1.0 - a)) * float(np.sqrt(2.0 / n))
    if n in _C0_TABLE:
        return _C0_TABLE[n][a]

    grid = np.asarray(C0_GRID, dtype=np.float64)
    values = np.array([_C0_TABLE[int(g)][a] for g in grid])
    # Linear in 1/sqrt(n): the grid is decreasing in that variable, so it
    # is reversed to keep np.interp's increasing-x contract.
    xs = 1.0 / np.sqrt(grid)
    order = np.argsort(xs)
    return float(np.interp(1.0 / np.sqrt(n), xs[order], values[order]))
